export const TAU = Math.PI * 2;

// 视觉收窄：真实包络线在剖面里几乎是一个圆，收 38% 才看得出三角
const RK = 1.38;

/** 缸体型线（2 叶外旋轮线），参数 t 从 0 到 2π */
export function epitrochoidPoint(t) {
  return [
    R * Math.cos(t) + E * Math.cos(3 * t),
    R * Math.sin(t) + E * Math.sin(3 * t)
  ];
}

export function epitrochoidPoints(n = 480, rot = 0) {
  const out = [];
  for (let i = 0; i < n; i++) {
    const t = (i / n) * TAU + rot;
    out.push(epitrochoidPoint(t));
  }
  return out;
}

/** 转子三叶廓线（局部坐标，每 120° 重复一次） */
export function rotorPoints() {
  const out = [];
  for (let k = 0; k < 3; k++) {
    const base = (k * TAU) / 3;
    for (let i = 0; i < 120; i++) {
      const a = base + (i * Math.PI) / 180;
      const r = Math.pow(ROTOR_R[i], RK);
      out.push([r * Math.cos(a), r * Math.sin(a)]);
    }
  }
  return out;
}

/** 转子某一片区（apex k → k+1）的廓线，局部坐标 */
export function rotorFlank(k, samples = 40) {
  const out = [];
  const base = (k * TAU) / 3;
  for (let i = 0; i <= samples; i++) {
    const idx = (i / samples) * 120;
    const i0 = Math.min(119, Math.floor(idx));
    const i1 = Math.min(119, i0 + 1);
    const f = idx - i0;
    const r = Math.pow(ROTOR_R[i0] * (1 - f) + ROTOR_R[i1] * f, RK);
    const a = base + (idx * Math.PI) / 180;
    out.push([r * Math.cos(a), r * Math.sin(a)]);
  }
  return out;
}
